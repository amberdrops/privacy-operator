# 조사. 레이블 값이나 역할어 뒤 이름 끝에 붙는 것을 떼어 낸다
JOSA_LONG = ("에게서", "에게", "한테", "께서", "으로", "이랑", "에서", "이나", "이며", "이고", "이다", "입니다")
JOSA_SHORT = ("은", "는", "이", "가", "을", "를", "의", "와", "과", "도", "만", "께", "랑", "로", "에", "님")


_PARENS = re.compile(r"\([^)]*\)|\[[^\]]*\]")


def normalize_header(text: str) -> str:
    return re.sub(r"[\s*:：·]", "", _PARENS.sub("", text or "")).lower()


def normalize_value(text: str) -> str:
    return re.sub(r"\s", "", text or "").lower()


def looks_like_name(token: str) -> bool:
    """성씨로 시작하는 한글 2~4자(두 글자 성씨면 3~5자)."""
    if not re.fullmatch(r"[가-힣]{2,5}", token or ""):
        return False
    if token in NOT_NAMES:
        return False
    if token[:2] in COMPOUND_SURNAMES:
        return 3 <= len(token) <= 5
    return token[0] in SURNAMES and len(token) <= 4


def strip_josa(token: str) -> str:
    """이름 끝 조사를 뗀다. 한 글자 조사는 4자 이상일 때만 뗀다(`김하은`의 '은'을 지키려고)."""
    for j in JOSA_LONG:
        if token.endswith(j) and len(token) - len(j) >= 2:
            return token[: -len(j)]
    if len(token) >= 4 and token[-1] in JOSA_SHORT:
        return token[:-1]
    return token
